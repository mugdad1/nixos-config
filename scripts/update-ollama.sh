#!/usr/bin/env bash
# Move pkgs/ollama-pins.nix to the latest ollama/ollama GitHub release.
#
# Called by `mcli update` before the rebuild. It touches nothing but the pins
# file, and restores it if any step fails, so a network hiccup cannot leave the
# repo with a half-written hash.
set -euo pipefail

REPO_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
PINS="$REPO_DIR/pkgs/ollama-pins.nix"
FAKE_HASH="sha256-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA="

info() { echo -e "\033[0;36m[INFO]\033[0m $*"; }
ok() { echo -e "\033[0;32m[OK]\033[0m $*"; }
die() {
    echo -e "\033[0;31m[ERROR]\033[0m $*" >&2
    exit 1
}

for tool in curl jq nix nix-prefetch-url; do
    command -v "$tool" > /dev/null || die "required tool not found: $tool"
done

current=$(sed -n 's/^[[:space:]]*version = "\(.*\)";/\1/p' "$PINS" | head -1)
[[ -n "$current" ]] || die "could not read the current version from $PINS"

tag=$(curl -fsSL https://api.github.com/repos/ollama/ollama/releases/latest | jq -r '.tag_name // empty')
[[ -n "$tag" ]] || die "GitHub did not return a latest release tag"
version=${tag#v}

if [[ "$version" == "$current" ]]; then
    ok "ollama already at the latest release (${version})"
    exit 0
fi

info "ollama ${current} -> ${version}"

llama_cpp=$(curl -fsSL "https://raw.githubusercontent.com/ollama/ollama/${tag}/LLAMA_CPP_VERSION")
[[ -n "$llama_cpp" ]] || die "could not read LLAMA_CPP_VERSION for ${tag}"

prefetch() {
    local url=$1
    local base32
    base32=$(nix-prefetch-url --unpack "$url" 2> /dev/null | tail -1)
    [[ -n "$base32" ]] || die "failed to prefetch $url"
    nix hash convert --hash-algo sha256 --to sri "$base32"
}

info "hashing ollama ${tag}..."
src_hash=$(prefetch "https://github.com/ollama/ollama/archive/refs/tags/${tag}.tar.gz")

info "hashing llama.cpp ${llama_cpp}..."
llama_hash=$(prefetch "https://github.com/ggml-org/llama.cpp/archive/refs/tags/${llama_cpp}.tar.gz")

backup=$(mktemp)
cp "$PINS" "$backup"
success=0
cleanup() {
    if [[ $success -eq 0 ]]; then
        cp "$backup" "$PINS"
    fi
    rm -f "$backup"
}
trap cleanup EXIT

write_pins() {
    local vendor=$1
    cat > "$PINS" << EOF
# Generated by scripts/update-ollama.sh — do not edit by hand.
# \`mcli update\` refreshes these pins from the latest ollama/ollama release.
{
  version = "${version}";

  srcHash = "${src_hash}";

  llamaCppVersion = "${llama_cpp}";
  llamaCppHash = "${llama_hash}";

  vendorHash = "${vendor}";
}
EOF
}

# The vendor hash is a property of the Go dependency graph, and buildGoModule
# only reveals it by failing a fixed-output build. Write a fake one, read the
# "got" hash, then write the real file.
write_pins "$FAKE_HASH"

info "resolving vendorHash for ollama ${version}..."
# Use the CPU package for this check: the vendor graph is identical, and it
# keeps cuda_nvcc out of the module-fetch closure.
build_output=$(
    nix build --impure --no-link --expr "
      let
        flake = builtins.getFlake \"${REPO_DIR}\";
        pkgs = flake.nixosConfigurations.victus.pkgs;
        pins = import (/. + \"${PINS}\");
      in
      (pkgs.ollama.overrideAttrs (old: {
        inherit (pins) version vendorHash;
        src = pkgs.fetchFromGitHub {
          owner = \"ollama\";
          repo = \"ollama\";
          tag = \"v\" + pins.version;
          hash = pins.srcHash;
        };
        passthru = old.passthru // {
          inherit (pins) llamaCppVersion;
          llamaCppSrc = pkgs.fetchFromGitHub {
            owner = \"ggml-org\";
            repo = \"llama.cpp\";
            tag = pins.llamaCppVersion;
            hash = pins.llamaCppHash;
          };
        };
      })).goModules
    " 2>&1 || true
)
vendor_hash=$(sed -n 's/^[[:space:]]*got:[[:space:]]*//p' <<< "$build_output" | tail -1)
if [[ -z "$vendor_hash" ]]; then
    echo "$build_output" >&2
    die "could not resolve vendorHash for ollama ${version}"
fi

write_pins "$vendor_hash"
success=1

ok "ollama pins now at ${version} (llama.cpp ${llama_cpp})"
